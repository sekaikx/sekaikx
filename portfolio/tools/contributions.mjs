// Fetch a GitHub user's public contribution calendar into assets/data/contributions.js.
//   node tools/contributions.mjs <github-username>
// Vercel runs this on every deploy (see vercel.json). If GitHub can't be reached, the
// existing file is left alone and the build carries on.
// Reads the same public page github.com shows on a profile; no token needed.
import { writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'assets', 'data', 'contributions.js');

// Pull [date, count] pairs out of the calendar markup. Each day is a <td data-date id> cell;
// its count lives in a <tool-tip for="that id"> ("5 contributions on ..." / "No contributions on ...").
// Older markup put the count straight on the cell as data-count.
export function parseCalendar(html) {
  const dateById = new Map(), direct = new Map();
  for (const [tag] of html.matchAll(/<td\b[^>]*\bdata-date="\d{4}-\d{2}-\d{2}"[^>]*>/g)) {
    const date = /data-date="([^"]+)"/.exec(tag)[1];
    const id = /\bid="([^"]+)"/.exec(tag);
    const count = /data-count="(\d+)"/.exec(tag);
    if (id) dateById.set(id[1], date);
    if (count) direct.set(date, Number(count[1]));
  }
  const counts = new Map(direct);
  for (const [, id, text] of html.matchAll(/<tool-tip\b[^>]*\bfor="([^"]+)"[^>]*>([^<]*)<\/tool-tip>/g)) {
    const date = dateById.get(id);
    if (!date) continue;
    const m = /([\d,]+)\s+contributions?/i.exec(text);
    counts.set(date, m ? Number(m[1].replace(/,/g, '')) : 0);
  }
  for (const date of dateById.values()) if (!counts.has(date)) counts.set(date, 0);
  return [...counts.entries()].sort((a, b) => a[0] < b[0] ? -1 : 1);
}

async function main() {
  const user = process.argv[2];
  if (!user || user.startsWith('-')) {
    console.error('Usage: node tools/contributions.mjs <github-username>');
    process.exit(1);
  }
  const res = await fetch(`https://github.com/users/${encodeURIComponent(user)}/contributions`, { headers: { 'User-Agent': 'sekaikx-portfolio' } });
  if (!res.ok) {
    console.error(`GitHub answered ${res.status} for "${user}". Check the username; the profile must be public.`);
    process.exit(1);
  }
  const days = parseCalendar(await res.text());
  if (!days.length) {
    console.error('Found no contribution calendar on that page. GitHub may have changed its markup; please open an issue.');
    process.exit(1);
  }
  const data = { sample: false, user, fetched: new Date().toISOString(), days };
  writeFileSync(OUT, `/* Generated by tools/contributions.mjs for ${user}. */\nwindow.PORTFOLIO_CONTRIBUTIONS = ${JSON.stringify(data)};\n`);
  const total = days.reduce((s, d) => s + d[1], 0);
  console.log(`Saved ${days.length} days (${total} contributions) for @${user} to assets/data/contributions.js`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
